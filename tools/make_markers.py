"""Printable ArUco marker sheets: assets/markers/markers.pdf.

    uv run tools/make_markers.py                 # paradise corner size, 20 mm tokens
    uv run tools/make_markers.py --token-mm 25

Page 1 has the four corner markers (two sets) for the board's corner holders;
page 2 has every token marker the engine accepts. IDs and the dictionary come
from engine/vision/markers.py, and the corner size from the scenario's
terrain.json (the holder pocket is cut for it), so regenerate after changing
either.

Each piece is a square to cut out on its dashed line: the marker plus a white
margin of one cell on every side, which is the quiet zone ArUco needs. The
PDF is vector (one filled path per marker, no embedded image), because a
rasterised sheet printed with the corner markers' borders eaten away on one
side and they never decoded.

Print at 100% ("Actual size"), not "Fit to page", and check the 100 mm bar
with a ruler. Glue pieces flat; curled paper won't decode either.
"""

import argparse
import json
import sys
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "engine"))
from vision.markers import CORNER_IDS, DICTIONARY, TOKEN_ID_START, TOKENS_PER_TYPE  # noqa: E402

PAGE_MM = (215.9, 279.4)  # US Letter, portrait
MARGIN_MM = 15.0
PT_PER_MM = 72 / 25.4
CELLS = 6  # 4x4 data bits plus a 1-cell black border
QUIET_CELLS = 1  # white margin on each side, part of the cut-out piece


def marker_bits(marker_id: int):
    """6x6 booleans, True = black, row 0 at the top."""
    img = cv2.aruco.generateImageMarker(cv2.aruco.getPredefinedDictionary(DICTIONARY), marker_id, CELLS)
    return img < 128


class Page:
    """Drawing in mm with y pointing down, written out as PDF operators."""

    def __init__(self) -> None:
        self.ops: list[str] = []

    def _xy(self, x: float, y: float) -> tuple[float, float]:
        return x * PT_PER_MM, (PAGE_MM[1] - y) * PT_PER_MM

    def rects(self, rects: list[tuple[float, float, float, float]], gray: float = 0.0) -> None:
        # All in one path and one fill, so abutting cells have no hairline seams.
        self.ops.append(f"{gray:.2f} g")
        for x, y, w, h in rects:
            px, py = self._xy(x, y + h)
            self.ops.append(f"{px:.3f} {py:.3f} {w * PT_PER_MM:.3f} {h * PT_PER_MM:.3f} re")
        self.ops.append("f")

    def dashed_box(self, x: float, y: float, w: float, h: float) -> None:
        px, py = self._xy(x, y + h)
        self.ops.append(f"q 0.6 G 0.3 w [2 2] 0 d {px:.3f} {py:.3f} {w * PT_PER_MM:.3f} {h * PT_PER_MM:.3f} re S Q")

    def line(self, x0: float, y0: float, x1: float, y1: float, width_mm: float = 0.3) -> None:
        a, b = self._xy(x0, y0)
        c, d = self._xy(x1, y1)
        self.ops.append(f"q 0 G {width_mm * PT_PER_MM:.3f} w {a:.3f} {b:.3f} m {c:.3f} {d:.3f} l S Q")

    def text(self, x: float, y: float, s: str, size: float = 8, gray: float = 0.0, bold: bool = False) -> None:
        px, py = self._xy(x, y)
        s = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        font = "F2" if bold else "F1"
        self.ops.append(f"BT {gray:.2f} g /{font} {size} Tf {px:.3f} {py:.3f} Td ({s}) Tj ET")

    def marker(self, marker_id: int, x: float, y: float, piece_mm: float, label: str) -> None:
        """A cut-out piece with its top-left at (x, y), label underneath."""
        cell = piece_mm / (CELLS + 2 * QUIET_CELLS)
        x0, y0 = x + QUIET_CELLS * cell, y + QUIET_CELLS * cell
        bits = marker_bits(marker_id)
        self.rects([(x0 + c * cell, y0 + r * cell, cell, cell) for r in range(CELLS) for c in range(CELLS) if bits[r, c]])
        self.dashed_box(x, y, piece_mm, piece_mm)
        self.text(x, y + piece_mm + 3.5, label, size=7)

    def header(self, title: str, note: str) -> None:
        self.text(MARGIN_MM, MARGIN_MM + 4, title, size=14, bold=True)
        self.text(MARGIN_MM, MARGIN_MM + 10, note, size=8, gray=0.3)

    def footer(self, dictionary_name: str) -> None:
        y = PAGE_MM[1] - MARGIN_MM - 8
        self.line(MARGIN_MM, y, MARGIN_MM + 100, y)
        for i in range(11):
            self.line(MARGIN_MM + 10 * i, y - (2.5 if i % 5 == 0 else 1.5), MARGIN_MM + 10 * i, y)
        self.text(MARGIN_MM + 103, y + 1, "100 mm: check with a ruler", size=7)
        self.text(
            MARGIN_MM,
            y + 6,
            f"Firewatch markers ({dictionary_name}). Print at 100% / Actual size, no scaling. "
            "Generated by tools/make_markers.py.",
            size=7,
            gray=0.4,
        )


def grid(page: Page, items: list[tuple[int, str]], piece_mm: float, top_mm: float, cols: int, gap_mm: float) -> float:
    """Lay pieces out in rows; returns the y below the last row."""
    row_h = piece_mm + 8
    for i, (marker_id, label) in enumerate(items):
        r, c = divmod(i, cols)
        page.marker(marker_id, MARGIN_MM + c * (piece_mm + gap_mm), top_mm + r * (row_h + gap_mm), piece_mm, label)
    rows = -(-len(items) // cols)
    return top_mm + rows * (row_h + gap_mm)


def corners_page(corner_mm: float) -> Page:
    p = Page()
    p.header(
        "Corner markers",
        f"Cut on the dashed line ({corner_mm:g} mm squares) and drop one into each corner holder's pocket. "
        "Second set is spare.",
    )
    items = [(i, f"{name}  (id {i})") for name, i in CORNER_IDS.items()]
    gap = 12.0
    cols = int((PAGE_MM[0] - 2 * MARGIN_MM + gap) // (corner_mm + gap))
    y = grid(p, items, corner_mm, MARGIN_MM + 20, cols, gap)
    grid(p, items, corner_mm, y + 6, cols, gap)
    p.footer("DICT_4X4_50")
    return p


def tokens_page(token_mm: float) -> Page:
    p = Page()
    p.header(
        "Token markers",
        f"Cut on the dashed line ({token_mm:g} mm squares) and glue flat on a token's top. "
        "Each ID is one physical token.",
    )
    y = MARGIN_MM + 20
    for kind, start in TOKEN_ID_START.items():
        p.text(MARGIN_MM, y + 3, kind.value.capitalize(), size=10, bold=True)
        items = [(start + k, f"{kind.value} {start + k}") for k in range(TOKENS_PER_TYPE)]
        y = grid(p, items, token_mm, y + 7, TOKENS_PER_TYPE, 10.0) + 2
    p.footer("DICT_4X4_50")
    return p


def write_pdf(pages: list[Page], path: Path) -> None:
    w, h = PAGE_MM[0] * PT_PER_MM, PAGE_MM[1] * PT_PER_MM
    n = len(pages)
    page_ids = [5 + 2 * i for i in range(n)]
    objs = {
        1: "<< /Type /Catalog /Pages 2 0 R >>",
        2: f"<< /Type /Pages /Kids [{' '.join(f'{i} 0 R' for i in page_ids)}] /Count {n} >>",
        3: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        4: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    }
    for pid, page in zip(page_ids, pages):
        stream = "\n".join(page.ops).encode()
        objs[pid] = (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {w:.2f} {h:.2f}] "
            f"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {pid + 1} 0 R >>"
        )
        objs[pid + 1] = stream
    out = bytearray(b"%PDF-1.4\n")
    offsets = {}
    for i in sorted(objs):
        offsets[i] = len(out)
        body = objs[i]
        if isinstance(body, bytes):
            out += f"{i} 0 obj\n<< /Length {len(body)} >>\nstream\n".encode() + body + b"\nendstream\nendobj\n"
        else:
            out += f"{i} 0 obj\n{body}\nendobj\n".encode()
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += b"".join(f"{offsets[i]:010d} 00000 n \n".encode() for i in sorted(objs))
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    path.write_bytes(bytes(out))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scenario", default="paradise", help="corner marker size comes from its terrain.json")
    ap.add_argument("--token-mm", type=float, default=20.0, help="token piece side, including the white margin")
    ap.add_argument("--out", type=Path, default=ROOT / "assets" / "markers" / "markers.pdf")
    args = ap.parse_args()

    terrain = json.loads((ROOT / "assets" / "scenarios" / args.scenario / "terrain.json").read_text())
    corner_mm = terrain["markers"]["marker_size_mm"]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_pdf([corners_page(corner_mm), tokens_page(args.token_mm)], args.out)
    cell = lambda piece: piece / (CELLS + 2 * QUIET_CELLS)
    print(
        f"wrote {args.out.relative_to(ROOT)}: corners {corner_mm:g} mm (cell {cell(corner_mm):.2f} mm), "
        f"tokens {args.token_mm:g} mm (cell {cell(args.token_mm):.2f} mm)"
    )


if __name__ == "__main__":
    main()
